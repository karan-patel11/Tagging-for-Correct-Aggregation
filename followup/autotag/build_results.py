"""STEP 6: write followup/autotag/RESULTS.md (and results/free_text.md) from the files the earlier
steps wrote. Every number in RESULTS.md comes from those files; nothing is typed in.

Inputs: results/cost_check.json, drafts/draft_{1,2,3}.yaml and their _meta.json, results/
D_autotag.jsonl (if M4 ran), eval/results/D.jsonl, tags/tags.yaml, PREREG.md (limits, verbatim).

Run: python followup/autotag/build_results.py
"""
import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))

import costs  # noqa: E402
import m4  # noqa: E402
import root_causes  # noqa: E402
import score_d  # noqa: E402
import score_tags  # noqa: E402

PREREG = HERE / "PREREG.md"
DRAFT_NAMES = ["draft_1", "draft_2", "draft_3"]

DEVIATIONS_PATH = HERE / "PREREG_DEVIATIONS.md"


def rel(p):
    p = Path(p).resolve()
    return str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)


def deviations():
    """The dated entries of PREREG_DEVIATIONS.md, with headings moved one level down to sit under
    RESULTS.md's "## Deviations"."""
    text = DEVIATIONS_PATH.read_text()
    body = text[text.index("\n## "):].strip()
    return re.sub(r"^## ", "### ", body, flags=re.M)


def known_limits():
    text = PREREG.read_text()
    m = re.search(r"^## Known limits\n(.*?)(?=^## |\Z)", text, flags=re.S | re.M)
    return m.group(1).strip()


def fmt(v):
    return "null" if v is None else (json.dumps(v) if not isinstance(v, str) else v)


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def questions_naming(runs_path, hand_entries, include_denominator=False):
    short = m4.short_metric_map(hand_entries)
    by_tag = {}
    for rec in score_d.load_records(runs_path).values():
        for tid in m4.named_tag_ids(rec, short, include_denominator):
            by_tag.setdefault(tid, set()).add(rec["question_id"])
    return {k: sorted(v) for k, v in by_tag.items()}


def build(drafts_dir, results_dir, out_path, free_text_path):
    paths = {n: drafts_dir / f"{n}.yaml" for n in DRAFT_NAMES}
    missing = [str(f) for n in DRAFT_NAMES for f in (paths[n], drafts_dir / f"{n}_meta.json")
               if not f.exists()]
    if missing:
        sys.exit(f"RESULTS.md needs all three drafts; missing: {missing}")
    cost_check = json.loads((results_dir / "cost_check.json").read_text())
    metas = {n: json.loads((drafts_dir / f"{n}_meta.json").read_text()) for n in DRAFT_NAMES}
    hand = score_tags.read_entries(score_tags.HAND_PATH)
    drafts = {n: score_tags.read_entries(p) for n, p in paths.items()}
    sc = score_tags.score_all(paths)
    D = sc["drafts"]
    L = ["# Results: auto-drafted tags, scored per field and end to end", "",
         "Generated by `followup/autotag/build_results.py` from the files listed in its docstring. "
         "Pre-registration: `followup/autotag/PREREG.md`. Hand tags (`tags/tags.yaml`) are the "
         "reference. Tagging model: " + cost_check["model"] + "; answering model unchanged.", ""]

    # ---- time and cost
    L += ["## Time and cost", "",
          f"Prices: USD per million tokens, read {cost_check['prices_read_on']} from "
          f"{cost_check['pricing_url']}: " + ", ".join(f"{k} ${v}" for k, v in
                                                      cost_check["prices_usd_per_mtok"].items()) + ".",
          f"System prefix: {cost_check['prefix_tokens']} tokens (token-counting endpoint); minimum "
          f"cacheable length {cost_check['min_cacheable_tokens']}; "
          + ("sent with cache_control." if cost_check["prefix_cached"]
             else "below the minimum, so sent without cache_control and not padded."), "",
          f"Cost check (one id, {cost_check['sample_call']['id']}): "
          f"${cost_check['sample_call']['cost_usd']:.6f}. Estimated total before drafting: "
          f"${cost_check['total_estimate_usd']:.4f} (upper bound ${cost_check['total_bound_usd']:.4f}); "
          f"cap at the cost check ${cost_check['cap_usd']:.2f}, cap for the runs "
          f"${costs.COST_CAP_USD:.2f} (see Deviations).", ""]
    rows = []
    for n in DRAFT_NAMES:
        t = metas[n]["tokens"]
        rows.append([n, metas[n]["wall_clock_seconds_this_process"], metas[n]["sum_call_seconds"],
                     t.get("input_tokens", 0), t.get("cache_creation_input_tokens", 0),
                     t.get("cache_read_input_tokens", 0), t.get("output_tokens", 0),
                     f"${metas[n]['cost_usd']:.4f}"])
    L += table(["draft", "wall-clock s", "sum of call s", "input", "cache write", "cache read",
                "output", "cost"], rows) + [""]
    d_path = results_dir / "D_autotag.jsonl"
    d_runs = score_d.load_records(d_path) if d_path.exists() else {}
    d_cost = sum(r.get("cost_usd", 0.0) for r in d_runs.values())
    total = cost_check["sample_call"]["cost_usd"] + sum(metas[n]["cost_usd"] for n in DRAFT_NAMES) + d_cost
    L += [f"Setup D on draft 1: {len(d_runs)} runs, ${d_cost:.4f}. Follow-up total: ${total:.4f}.", ""]
    notes = {n: metas[n]["parse_notes"] for n in DRAFT_NAMES if metas[n]["parse_notes"]}
    if notes:
        L += ["Parse notes: " + "; ".join(f"{n} {k}: {', '.join(v)}" for n, d in notes.items()
                                           for k, v in d.items()), ""]

    # ---- M1
    L += ["## M1: per-field match on the 12 measures", "",
          "Cells are matches / measures scored. Presence fields are scored only on measures where "
          "the hand tag has a value, and count a match when the draft has any value.", ""]
    rows = []
    for f in score_tags.M1_FIELDS:
        cells = []
        for n in DRAFT_NAMES:
            vals = [row[f]["match"] for row in D[n]["m1"].values() if f in row]
            cells.append(f"{sum(vals)}/{len(vals)}")
        rows.append([f] + cells)
    L += table(["field"] + DRAFT_NAMES, rows) + ["", "Mismatches:", ""]
    rows = []
    for n in DRAFT_NAMES:
        for tid, row in D[n]["m1"].items():
            for f, v in row.items():
                if not v["match"]:
                    extra = (f" (extra {v['extra']}, missing {v['missing']})"
                             if f == "valid_methods" else "")
                    rows.append([n, tid, f, fmt(v["hand"]), fmt(v["draft"]) + extra])
    L += (table(["draft", "measure", "field", "hand", "draft value"], rows) if rows else ["none"]) + [""]

    # ---- M1b
    L += ["## M1b: semantic_type on the 31 dimension/identifier entries", ""]
    L += table(["draft", "matches"], [[n, f"{sum(v['match'] for v in D[n]['m1b'].values())}/"
                                          f"{len(D[n]['m1b'])}"] for n in DRAFT_NAMES]) + [""]
    rows = [[n, tid, v["hand"], fmt(v["draft"])] for n in DRAFT_NAMES
            for tid, v in D[n]["m1b"].items() if not v["match"]]
    L += ["Mismatches:", ""] + (table(["draft", "entry", "hand", "draft value"], rows)
                                if rows else ["none"]) + [""]

    # ---- M2
    naming = questions_naming(score_d.HAND_D, hand)
    naming2 = questions_naming(score_d.HAND_D, hand, include_denominator=True)
    L += ["## M2: dangerous errors", "",
          "Questions: those whose hand-tag setup D runs named the tag id in a tool call through "
          "metric_id or get_metric's metric (pre-registered count). \"+ denominator_id\": questions "
          "added when aggregate's denominator_id also counts (secondary count, reporting only; "
          "see Deviations).", ""]
    rows = []
    for n in DRAFT_NAMES:
        for tid, errs in D[n]["m2"].items():
            for e in errs:
                val = fmt(e["draft"]) + (f" (allows {e['forbidden_allowed']})"
                                         if "forbidden_allowed" in e else "")
                extra = sorted(set(naming2.get(tid, [])) - set(naming.get(tid, [])))
                rows.append([n, tid, e["field"], fmt(e["hand"]), val,
                             ", ".join(naming.get(tid, [])) or "none", ", ".join(extra) or "none"])
    counts = [f"{n}: {sum(len(v) for v in D[n]['m2'].values())} errors on "
              f"{sum(1 for v in D[n]['m2'].values() if v)} of {len(D[n]['m2'])} measures"
              for n in DRAFT_NAMES]
    L += ["; ".join(counts) + ".", ""]
    qrows = []
    for n in DRAFT_NAMES:
        bad = [tid for tid, v in D[n]["m2"].items() if v]
        q1 = sorted({q for tid in bad for q in naming.get(tid, [])})
        q2 = sorted({q for tid in bad for q in naming2.get(tid, [])})
        qrows.append([n, len(q1), len(q2), ", ".join(sorted(set(q2) - set(q1))) or "none"])
    L += ["Distinct questions affected by a dangerous error:", ""]
    L += table(["draft", "pre-registered count", "secondary count (+ denominator_id)",
                "questions added by denominator_id"], qrows) + [""]
    L += (table(["draft", "measure", "field", "hand", "draft value", "questions",
                 "+ denominator_id"], rows) if rows else ["none"]) + [""]

    # ---- M3
    L += ["## M3: validation (load_tags, check_tags_against_db)", ""]
    L += table(["draft", "load_tags", "entries failing alone", "db problems", "result"],
               [[n, "ok" if D[n]["m3"]["load_tags_ok"] else "fails", len(D[n]["m3"]["entry_errors"]),
                 len(D[n]["m3"]["db_problems"]), "pass" if D[n]["m3"]["pass"] else "FAIL"]
                for n in DRAFT_NAMES]) + [""]
    for n in DRAFT_NAMES:
        r = D[n]["m3"]
        items = [f"{k}: {e}" for k, es in r["entry_errors"].items() for e in es] + r["db_problems"]
        if items:
            L += [f"{n} failures:", ""] + [f"- {x}" for x in items] + [""]

    # ---- M4
    L += ["## M4: setup D end to end on draft 1", ""]
    if not D["draft_1"]["m3"]["pass"]:
        L += ["draft_1 fails M3, so M4 was not run (PREREG). The M3 failures above are the M4 "
              "result.", ""]
    else:
        hand_scored, _, _ = score_d.score_records(score_d.HAND_D)
        draft_scored, draft_runs, _ = score_d.score_records(d_path)
        hc, dc = sum(s["correct"] for s in hand_scored.values()), sum(s["correct"] for s in draft_scored.values())
        L += table(["tags", "correct", "runs"], [["hand (eval/results/D.jsonl)", hc, len(hand_scored)],
                                                 ["draft_1 (results/D_autotag.jsonl)", dc, len(draft_scored)]])
        L += [""]
        if len(draft_scored) != len(hand_scored):
            L += [f"draft_1 has {len(draft_scored)} runs, not {len(hand_scored)}; missing runs count "
                  "as not correct.", ""]
        ch = m4.changed_outcomes(hand_scored, draft_scored, draft_runs, hand, drafts["draft_1"])
        cls = Counter(r["class"] for v in ch.values() for r in v["incorrect_draft_runs"])
        L += [f"Questions with a changed outcome: {len(ch)}.", ""]
        L += table(["class"] + ["incorrect draft-1 runs on changed questions"],
                   [[c, cls.get(c, 0)] for c in m4.CLASSES]) + [""]
        rows = []
        for qid, v in ch.items():
            runs = v["incorrect_draft_runs"]
            detail = "; ".join(f"run {r['run']}: {r['class']}"
                               + (" [" + ", ".join(f"{t}: {'/'.join(fs)}" for t, fs in r["linked"].items()) + "]"
                                  if r["linked"] else " [no differing tag named]") for r in runs) or "-"
            rows.append([qid, f"{v['hand_correct']}/3", f"{v['draft_correct']}/3", detail])
        L += (table(["question", "hand", "draft_1", "incorrect draft-1 runs: class [tag id: differing fields]"],
                    rows) if rows else ["none"]) + [""]
        # Secondary count (reporting only): links that appear only when denominator_id counts.
        sec = []
        for qid, v in ch.items():
            for r in v["incorrect_draft_runs"]:
                rec = draft_runs[(qid, r["run"])]
                both = m4.linked_fields(rec, hand, drafts["draft_1"], include_denominator=True)
                only = {t: fs for t, fs in both.items() if t not in r["linked"]}
                if only:
                    sec.append([qid, r["run"], ", ".join(f"{t}: {'/'.join(fs)}" for t, fs in only.items())])
        n_runs = sum(len(v["incorrect_draft_runs"]) for v in ch.values())
        n_pri = sum(1 for v in ch.values() for r in v["incorrect_draft_runs"] if r["linked"])
        n_sec = len({(q, r) for q, r, _ in sec} | {(q, r["run"]) for q, v in ch.items()
                                                    for r in v["incorrect_draft_runs"] if r["linked"]})
        L += [f"Incorrect draft-1 runs linked to a differing tag: {n_pri} of {n_runs} "
              f"(pre-registered count); {n_sec} of {n_runs} when aggregate's denominator_id also "
              f"counts (secondary count). Links added by denominator_id:", ""]
        L += (table(["question", "run", "tag id: differing fields"], sec) if sec else ["none"]) + [""]

    # ---- verdicts
    L += ["## Per-field verdict: auto-draft vs human review", "",
          "\"safe to auto-draft\" only if all 3 drafts match the hand tag on every entry scored for "
          "that field; otherwise \"needs human review\". This threshold is a choice made in "
          "PREREG.md, not an industry standard.", ""]
    L += table(["field", "entries scored per draft", "verdict"],
               [[f, v["entries_per_draft"]["draft_1"], v["verdict"]] for f, v in sc["verdicts"].items()]) + [""]

    # ---- free text, limits, deviations
    L += ["## Free-text fields", "",
          f"description, derivation and lineage are not scored; all three drafts are listed next to "
          f"the hand text in `{rel(free_text_path)}` for a manual read.", ""]
    if D["draft_1"]["m3"]["pass"]:
        L += root_causes.section_lines()
    L += ["## Known limits (verbatim from PREREG.md)", "", known_limits(), ""]
    L += ["## Deviations", "", f"From `{rel(DEVIATIONS_PATH)}`.", "", deviations(), ""]
    out_path.write_text("\n".join(L))

    F = ["# Free-text fields for a manual read", "",
         "Generated by `followup/autotag/build_results.py`. Not scored.", ""]
    d_by = {n: {e["id"]: e for e in drafts[n] if isinstance(e, dict) and "id" in e} for n in DRAFT_NAMES}
    for h in hand:
        F += [f"## {h['id']}", ""]
        for f in ("description", "derivation", "lineage"):
            F += [f"- hand {f}: {fmt(h.get(f))}"]
            F += [f"- {n} {f}: {fmt(d_by[n].get(h['id'], {}).get(f))}" for n in DRAFT_NAMES]
        F += [""]
    free_text_path.write_text("\n".join(F))
    print(f"wrote {out_path} and {free_text_path}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--drafts-dir", type=Path, default=HERE / "drafts")
    ap.add_argument("--results-dir", type=Path, default=HERE / "results")
    ap.add_argument("--out", type=Path, default=HERE / "RESULTS.md")
    ap.add_argument("--free-text", type=Path, default=HERE / "results" / "free_text.md")
    a = ap.parse_args()
    build(a.drafts_dir, a.results_dir, a.out, a.free_text)


if __name__ == "__main__":
    main()
