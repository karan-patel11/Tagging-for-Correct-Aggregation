"""Write docs/key.md: setups, terms, and the text of every question ID that README.md or
docs/error_analysis.md mentions, plus the IDs in REQUESTED.

Question texts and categories are read from eval/questions.yaml at build time; the build fails if a
mentioned ID is not in that file. Ranges such as q022-q024 or q022–q024 are expanded.

Run: python report/build_key.py
"""

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
QUESTIONS = ROOT / "eval" / "questions.yaml"
SOURCES = [ROOT / "README.md", ROOT / "docs" / "error_analysis.md"]
OUT = ROOT / "docs" / "key.md"
# IDs the author asked to list (the error analysis, README and results-page replays refer to them);
# IDs found in SOURCES are added to these.
REQUESTED = ["q003", "q007", "q010", "q012", "q014", "q016", "q017", "q018", "q022", "q023", "q024",
             "q030", "q031", "q034", "q038"]

SETUPS = """\
- **A · Schema only:** the model sees the table schema and writes SQL.
- **B · Prose descriptions:** the schema plus prose sentences generated from the tags, one sentence per fact; writes SQL.
- **C · Tags file:** the schema plus the tags file itself; writes SQL.
- **D · Semantic tools:** no SQL; four tools (`list_metrics`, `describe_column`, `get_metric`, `aggregate`) that read the tags and apply their rules.
"""

TERMS = """\
- **Tag:** a rule attached to a metric in `tags/tags.yaml`, for example that total assets is a balance whose yearly value is the last quarter-end balance, never a sum across quarters.
- **FINAL line:** the last line of every run, a JSON object with `answer` (a number or null), `unit`, `warning` and `refused`. Only this line is scored.
- **warning:** `warning=true` means the model attached a caveat to its number.
- **refused:** `refused=true` means the model declined to give a number.
- **Expected behaviour:** each question's key expects `answer`, `answer_with_warning` (a number and warning=true) or `refuse`.
- **Trap and trap name:** a stored trap is a specific wrong answer computed in advance for a question (in `trap_answers` in `eval/questions.yaml`). Its name says how it is produced, e.g. `sum_of_4_quarter_ends` (adding quarter-end balances) or `used_fy_value` (the full-year figure where a quarter was asked). A run hits a trap when its number is within the question's tolerance of that wrong answer.
- **YTD6 / YTD9:** year-to-date rows covering the first six or nine months of a fiscal year, as filed in 10-Qs. A single quarter is derived by subtraction (e.g. Q3 = YTD9 − YTD6).
- **Ratio of sums:** a combined margin computed as total operating income ÷ total revenue across companies, not the mean of each company's margin (the `mean_of_margins` trap).
- **Warnings on questions whose key expects no caveat** (called over-warning in `eval/score.py` and `summary.md`): runs with warning=true on a question whose expected behaviour is `answer`. They are not scored as errors. Most cite stored filing dates or retrieval metadata (keyword heuristic, `report/analyze_over_warnings.py`); the dataset keeps the latest-filed value, so prior-year figures carry later filings' dates.
- **Majority vote:** a setup counts as right on a question when more than half of its runs on that question are correct (2 of 3).
- **max_tokens:** the API stop reason when a response reaches the output-token limit; a run that stops this way before writing a FINAL line is unparsed and scored incorrect.
"""


def mentioned_ids(text):
    ids = set()
    for a, b in re.findall(r"\bq(\d{3})\s*[-–]\s*q(\d{3})\b", text):
        ids.update(f"q{i:03d}" for i in range(int(a), int(b) + 1))
    ids.update(re.findall(r"\bq\d{3}\b", text))
    return ids


def main():
    questions = {q["id"]: q for q in yaml.safe_load(QUESTIONS.read_text())}
    ids = set(REQUESTED)
    for p in SOURCES:
        ids |= mentioned_ids(p.read_text())
    missing = sorted(i for i in ids if i not in questions)
    if missing:
        sys.exit(f"build_key: IDs not in eval/questions.yaml: {missing}")
    rows = "\n".join(
        f"| {i} | {questions[i]['category']} | {questions[i]['expected_behavior']} | "
        f"{questions[i]['question'].replace('|', '/')} |" for i in sorted(ids))
    OUT.write_text(f"""# Key: setups, terms and question texts

Generated by `report/build_key.py`. Question texts are read from `eval/questions.yaml`; q017 means
question 17 in that file.

## Setups

{SETUPS}
## Terms

{TERMS}
## Questions referred to in the README, the error analysis and the results page

| ID | Category | Expected behaviour | Question |
|---|---|---|---|
{rows}
""")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(ids)} questions: {', '.join(sorted(ids))})")


if __name__ == "__main__":
    main()
